"""The lock files must stay consistent with the ranges and with what the Docker images and CI install.

Backend: `backend/requirements.in` holds the version ranges, `backend/requirements.txt` is generated from it
(pip-compile --generate-hashes, Python 3.12) and is what the image installs with `--require-hashes`.
Web: `web/package.json` and `web/package-lock.json`; the image and CI use `npm ci`.

When one of these tests fails after a dependency change, the lock file is out of date: regenerate it (Dependabot does it for
its own pull requests; docs/DEVELOPMENT.md, "Lock files", says how otherwise). No network access is needed here.
"""
import json
import re
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
WEB = ROOT / "web"


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def ranges() -> dict:
    found = {}
    for raw in read(BACKEND / "requirements.in").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            requirement = Requirement(line)
            found[canonicalize_name(requirement.name)] = requirement
    return found


def locked() -> dict:
    """name -> (version, number of sha256 hashes) for every pinned package in backend/requirements.txt."""
    pins, current = {}, None
    for line in read(BACKEND / "requirements.txt").splitlines():
        pin = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s\\]+)", line)
        if pin:
            current = canonicalize_name(pin.group(1))
            pins[current] = [pin.group(2), 0]
        elif current and line.strip().startswith("--hash=sha256:"):
            pins[current][1] += 1
    return {name: (version, hashes) for name, (version, hashes) in pins.items()}


def test_every_range_is_satisfied_by_the_locked_version():
    pins = locked()
    assert pins, "backend/requirements.txt has no pinned packages"
    for name, requirement in ranges().items():
        assert name in pins, f"{name} is in requirements.in but not in the lock file requirements.txt"
        version = pins[name][0]
        assert requirement.specifier.contains(version, prereleases=True), (
            f"requirements.txt pins {name}=={version}, outside the range {requirement.specifier} in requirements.in: regenerate the lock file")


def test_every_locked_package_has_checksums_and_nothing_is_unpinned():
    for name, (version, hashes) in locked().items():
        assert hashes >= 1, f"{name}=={version} has no --hash=sha256: lines"
    for raw in read(BACKEND / "requirements.txt").splitlines():
        line = raw.strip()
        if not line or line.startswith(("#", "--hash=")) or line == "\\":
            continue
        assert re.match(r"^[A-Za-z0-9_.\-]+==[^\s\\]+( \\)?$", line) or line.startswith("--"), f"requirements.txt line is not an exact pin: {line}"


def test_the_backend_lock_was_made_for_the_python_of_the_image():
    header = "\n".join(read(BACKEND / "requirements.txt").splitlines()[:6])
    assert "autogenerated by pip-compile with Python 3.12" in header
    assert "--generate-hashes" in header
    assert re.search(r"^FROM python:3\.12(-|$)", read(BACKEND / "Dockerfile"), re.M)


def test_the_backend_image_installs_only_hashed_exact_versions():
    dockerfile = read(BACKEND / "Dockerfile")
    assert "pip install --no-cache-dir --require-hashes -r requirements.txt" in dockerfile
    assert not re.search(r"^(RUN|COPY)\b.*requirements\.in", dockerfile, re.M)  # the ranges are never what the image installs


def test_ci_tests_run_on_the_locked_versions_first():
    ci = read(ROOT / ".github" / "workflows" / "ci.yml")
    assert ci.index("pip install --require-hashes -r backend/requirements.txt") < ci.index("pip install -r backend/requirements-test.txt")
    assert "-r requirements.in" in read(BACKEND / "requirements-test.txt")


def test_the_web_lock_matches_package_json_and_has_integrity_hashes():
    package = json.loads(read(WEB / "package.json"))
    lock = json.loads(read(WEB / "package-lock.json"))
    assert lock["lockfileVersion"] == 3
    root = lock["packages"][""]
    assert root.get("dependencies", {}) == package.get("dependencies", {}), "package-lock.json does not match package.json dependencies"
    assert root.get("devDependencies", {}) == package.get("devDependencies", {}), "package-lock.json does not match package.json devDependencies"
    for path, entry in lock["packages"].items():
        if path and not entry.get("link"):
            assert entry.get("resolved") and entry.get("integrity", "").startswith("sha"), f"{path} has no resolved URL or integrity hash"


def test_the_web_image_and_ci_install_the_lock_file_exactly():
    dockerfile = read(WEB / "Dockerfile")
    assert "COPY package.json package-lock.json ./" in dockerfile
    assert "npm ci" in dockerfile and "npm install" not in dockerfile
    ci = read(ROOT / ".github" / "workflows" / "ci.yml")
    assert "npm ci --no-audit --no-fund" in ci and "npm install --no-audit" not in ci
